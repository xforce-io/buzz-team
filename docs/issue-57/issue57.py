    v.add_argument("--new-policy", default=str(Path(__file__).with_name(POLICY_NAME)))
    v.add_argument("--inventory", default=str(INVENTORY))
    v.add_argument("--rule")
    v.add_argument("--prompt", choices=("present", "absent", "skip"), default="skip")
    v.add_argument("--thin-python")
    v.add_argument("--static-only", action="store_true")
    v.add_argument("--old-sha", default=OLD_SHA)
    v.add_argument("--baseline", help="JSON {name: sha256} for the other 8 policies (default: baseline-before)")
    v.add_argument("--compare-state")
    v.add_argument("--restarted", action="store_true")
    v.add_argument("--ps-fixture", default=os.environ.get("ISSUE57_TEST_PS_FIXTURE"))
    i = sub.add_parser("insert-rule")
    i.add_argument("--inventory", required=True)
    i.add_argument("--rule", required=True)
    args = parser.parse_args(argv)
    try:
        if args.cmd == "precheck":
            info = precheck(Path(args.policy), Path(args.grok_home), Path(args.cwd),
                            Path(args.profile_out) if args.profile_out else None)
            text = json.dumps(info, ensure_ascii=False, indent=2)
            if args.json_out:
                Path(args.json_out).write_text(text + "\n")
            print(text)
            print(f"PRECHECK PASS policy_sha256={info['policy_sha256']} profile_sha256={info['profile_sha256']}")
            return 0
        if args.cmd == "snapshot":
            rule = Path(args.rule).read_text() if args.rule else None
            snap = snapshot(Path(args.policies), Path(args.inventory), rule, args.ps_fixture)
            if args.out:
                Path(args.out).write_text(json.dumps(snap, ensure_ascii=False, indent=2) + "\n")
            print_snapshot(snap)
            return 0
        if args.cmd == "verify":
            return verify(args)
        if args.cmd == "insert-rule":
            rows = insert_inventory(Path(args.inventory), Path(args.rule).read_text())
            print(f"issue57: rule inserted into managed-agents rows {rows}")
            return 0
    except (OSError, ValueError, KeyError) as exc:
        print(f"issue57 {args.cmd}: FAIL {exc}", file=sys.stderr)
        return 1
    return 2


