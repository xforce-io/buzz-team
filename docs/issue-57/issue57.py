def sha256_file(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


# ---------------------------------------------------------------- policy precheck (thin code)

def precheck(policy: Path, grok_home: Path, cwd: Path, profile_out: Path | None = None) -> dict:
    """Validate `policy` and render the Seatbelt profile with the running buzz_team.thin."""
    from buzz_team import thin  # the module the live launcher imports

    env = {"BUZZ_TEAM_POLICY_PATH": str(policy), "GROK_HOME": str(grok_home), "GROK_ACP_CWD": str(cwd)}
    policy_file, home, executable, roots = thin._load_policy(env)
    profile = thin._profile(roots)
    via = "thin._profile(roots) after thin._load_policy(env)"
    if thin.SEATBELT.is_file():
        argv, runtime_env, _ = thin.command(env, ["agent", "stdio"])
        if argv[:2] != [str(thin.SEATBELT), "-p"] or argv[2] != profile:
            raise ValueError("thin.command profile differs from thin._profile")
        via = "thin.command(env, ['agent','stdio'])[2] (== thin._profile(roots))"
        tmpdir = runtime_env["TMPDIR"]
    else:
        tmpdir = str(home.parent / "tmp") + "/"
    module = Path(thin.__file__)
    info = {"thin_module": str(module), "thin_py_sha256": sha256_file(module), "rendered_by": via,
            "python": sys.version.split()[0], "package": _package_origin(module),
            "policy": str(policy_file), "policy_sha256": sha256_file(policy_file),
            "policy_mode": oct(policy_file.stat().st_mode & 0o777), "grok_home": str(home),
            "grok_executable": str(executable), "roots": [str(r) for r in roots], "tmpdir": tmpdir,
            "profile_sha256": hashlib.sha256(profile.encode()).hexdigest()}
    write_paths = [Path(p) for p in json.loads(policy_file.read_text())["write_paths"]]
    for i, a in enumerate(write_paths):
        for b in write_paths[i + 1:]:
            if a == b or _relative(a, b) or _relative(b, a):
                raise ValueError(f"write paths overlap: {a} {b}")
    if profile_out:
        Path(profile_out).write_text(profile)
    return info


def _relative(a: Path, b: Path) -> bool:
    try:
        a.relative_to(b)
        return True
    except ValueError:
        return False


def _package_origin(module: Path) -> dict:
    site = module.parent.parent
    for dist in sorted(site.glob("buzz_team-*.dist-info")):
        out = {"dist_info": dist.name}
        direct = dist / "direct_url.json"
        if direct.is_file():
            data = json.loads(direct.read_text())
            out["url"] = data.get("url", "")
            match = re.search(r"/([0-9a-f]{40})/", out["url"])
            if match:
                out["package_sha"] = match.group(1)
        return out
    return {"dist_info": None}


# ---------------------------------------------------------------- processes

def _env_subset(text: str, keys) -> dict:
    found = {}
    for key in keys:
        match = re.search(r"(?:^|\s)" + re.escape(key) + r"=(\S*)", text)
        if match:
            found[key] = match.group(1)
    return found


def _run(argv) -> str:
    try:
        return subprocess.run(argv, capture_output=True, text=True, check=False).stdout
    except OSError:
        return ""


def list_processes(fixture: str | None = None) -> list:
    """buzz-acp processes with whitelisted env, TCP state and grok children."""
    if fixture:
        return json.loads(Path(fixture).read_text())
    procs = []
    for line in _run(["ps", "-axww", "-o", "pid=,ppid=,comm="]).splitlines():
        parts = line.split(None, 2)
        if len(parts) == 3 and parts[2].rsplit("/", 1)[-1] == "buzz-acp":
            procs.append(_describe(int(parts[0]), int(parts[1])))
    return sorted(procs, key=lambda p: p["pid"])


def _describe(pid: int, ppid: int) -> dict:
    env = _env_subset(_run(["ps", "-E", "-ww", "-o", "command=", "-p", str(pid)]), ACP_KEYS)
    tcp = [l.split(None, 8)[-1] for l in _run(["lsof", "-nP", "-a", "-p", str(pid), "-i", "TCP"]).splitlines()[1:]]
    children = []
    for c in _run(["pgrep", "-P", str(pid)]).split():
        children.append({"pid": int(c), "comm": _run(["ps", "-o", "comm=", "-p", c]).strip(),
                         "env": _env_subset(_run(["ps", "-E", "-ww", "-o", "command=", "-p", c]), CHILD_KEYS)})
    return {"pid": pid, "ppid": ppid, "lstart": _run(["ps", "-o", "lstart=", "-p", str(pid)]).strip(),
            "env": env, "tcp": tcp, "children": children}


def seat_of(proc: dict) -> str:
    policy = proc["env"].get("BUZZ_TEAM_POLICY_PATH", "")
    if policy:
        return Path(policy).name.replace("-seatbelt.json", "")
    home = proc["env"].get("GROK_HOME", "")
    return "zhouheng" if home == str(ZH_IDENTITY / "grok") else "?"


def relay_of(proc: dict) -> str:
    url = proc["env"].get("BUZZ_RELAY_URL", "").rstrip("/")
    for name, value in RELAYS.items():
        if url == value:
            return name
    return url or "?"


def is_zhouheng(proc: dict) -> bool:
    return proc["env"].get("GROK_HOME") == str(ZH_IDENTITY / "grok") or seat_of(proc) == "zhouheng"


def relay_state(proc: dict) -> str:
    if relay_of(proc) == "local":
        ok = any(f"->127.0.0.1:{LOCAL_PORT}" in t and "ESTABLISHED" in t for t in proc["tcp"])
        return "ESTABLISHED :3000" if ok else "NOT CONNECTED :3000"
    return "; ".join(proc["tcp"]) or "no TCP socket"


def policy_shas(policies: Path) -> dict:
    return {p.name: sha256_file(p) for p in sorted(Path(policies).glob("*.json"))}


def prompt_rows(inventory: Path, rule: str | None = None) -> list:
    rows = []
    try:
        data = json.loads(Path(inventory).read_text())
    except (OSError, ValueError):
        return rows
    for index, row in enumerate(data):
        if row.get("slug") == ZH_PERSONA or row.get("persona_id") == ZH_PERSONA:
            prompt = row.get("system_prompt") or ""
            rows.append({"index": index, "relay_url": row.get("relay_url") or "", "prompt_sha256":
                         hashlib.sha256(prompt.encode()).hexdigest(),
                         "rule_count": prompt.count(rule.strip()) if rule else None})
    return rows


def log_sizes() -> dict:
    return {p.name: p.stat().st_size for p in sorted(LOG_DIR.glob(ZH_PUB + "__*.log"))} if LOG_DIR.is_dir() else {}


def snapshot(policies: Path, inventory: Path, rule: str | None, fixture: str | None) -> dict:
    procs = list_processes(fixture)
    for p in procs:
        p["seat"], p["relay"], p["relay_state"] = seat_of(p), relay_of(p), relay_state(p)
    return {"fixture": bool(fixture), "processes": procs, "policies": policy_shas(policies),
            "zhouheng_prompt_rows": prompt_rows(inventory, rule), "zhouheng_logs": log_sizes()}


