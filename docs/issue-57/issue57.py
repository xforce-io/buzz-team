# ---------------------------------------------------------------- prompt rule

def insert_rule(prompt: str, rule: str) -> str:
    """Append `rule` as the last line of the last '## 长任务执行与恢复' section."""
    line = rule.strip()
    if line in prompt:
        raise ValueError("rule already present")
    lines = prompt.split("\n")
    starts = [i for i, text in enumerate(lines) if text.startswith(SECTION)]
    if not starts:
        raise ValueError("section not found: " + SECTION)
    end = len(lines)
    for i in range(starts[-1] + 1, len(lines)):
        if lines[i].startswith("#"):
            end = i
            break
    last = max(i for i in range(starts[-1], end) if lines[i].strip())
    return "\n".join(lines[:last + 1] + [line] + lines[last + 1:])


def insert_inventory(inventory: Path, rule: str) -> list:
    data = json.loads(inventory.read_text())
    touched = []
    for index, row in enumerate(data):
        if row.get("slug") == ZH_PERSONA or row.get("persona_id") == ZH_PERSONA:
            row["system_prompt"] = insert_rule(row.get("system_prompt") or "", rule)
            touched.append(index)
    if len(touched) != 2:
        raise ValueError(f"expected 2 周衡 rows, found {touched}")
    tmp = inventory.with_name(inventory.name + ".issue57-new")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=2))
    os.chmod(tmp, inventory.stat().st_mode & 0o777)
    tmp.replace(inventory)
    return touched


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="issue57")
    sub = parser.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("precheck")
    p.add_argument("--policy", required=True)
